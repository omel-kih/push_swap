#include "libft.h"

void	*ft_memchr(const void *s, int c, size_t n)
{
	size_t				i;
	const unsigned char	*chr;

	i = 0;
	chr = (const unsigned char *)s;
	while (i < n)
	{
		if (chr[i] == (const unsigned char)c)
			return ((void *)&chr[i]);
		i++;
	}
	return (NULL);
}
