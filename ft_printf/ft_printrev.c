#include "ft_printf.h"

void	ft_printrev(char *buf, t_data *data, int i)
{
	while (i > 0)
	{
		i--;
		if (write(1, &buf[i], 1) == -1)
		{
			data->s = -1;
			return ;
		}
		data->s++;
	}
}
